import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { UI_LANGUAGES } from '../src/shared/ui-languages.ts'
import { uiCatalogIssues } from '../src/shared/ui-catalog-validation.ts'

const directory = fileURLToPath(new URL('../src/shared/locales/', import.meta.url))
const source = JSON.parse(readFileSync(`${directory}en.json`, 'utf8'))
const keys = Object.keys(source)
let errors = 0
const problem = (message) => { errors++; console.error(message) }
for (const language of UI_LANGUAGES) {
  const file = `${directory}${language.code}.json`
  if (!existsSync(file)) { problem(`${language.code}: catalog missing`); continue }
  const catalog = JSON.parse(readFileSync(file, 'utf8'))
  for (const key of keys) {
    for (const issue of uiCatalogIssues(language.code, key, catalog[key])) problem(`${language.code}: ${issue} in ${JSON.stringify(key)}`)
  }
  for (const key of Object.keys(catalog)) if (!(key in source)) problem(`${language.code}: obsolete key ${JSON.stringify(key)}`)
}
if (process.argv.includes('--write-index')) {
  const available = UI_LANGUAGES.filter((l) => existsSync(`${directory}${l.code}.json`))
  writeFileSync(`${directory}index.ts`, '// Offline interface catalogs. Generated by scripts/check-ui-locales.mjs --write-index.\n' +
    "import type { UiLanguage } from '../ui-languages'\n" +
    available.map((l) => `import ${l.code} from './${l.code}.json' with { type: 'json' }`).join('\n') + '\n\n' +
    `export const catalogs: Partial<Record<UiLanguage, Record<string, string>>> = { ${available.map((l) => l.code).join(', ')} }\n`)
}
console.log(`${UI_LANGUAGES.length} languages · ${keys.length} messages per catalog · ${errors} problems`)
process.exitCode = errors ? 1 : 0
